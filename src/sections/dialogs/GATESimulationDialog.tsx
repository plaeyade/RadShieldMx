// =============================================================================
// GATESimulationDialog.tsx — GATE Simulation for PET and SPECT
// OpenGATE v9.4+ — Geant4 Application for Tomographic Emission
// PET/CT, SPECT, CBCT, Linac dose, Time management
// =============================================================================
import { useState, useCallback, useMemo } from 'react';
import {
  Dialog, DialogContent, DialogHeader, DialogTitle,
} from '@/components/ui/dialog';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';
import { Tabs, TabsContent, TabsList, TabsTrigger } from '@/components/ui/tabs';
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';
import { Badge } from '@/components/ui/badge';
import { Separator } from '@/components/ui/separator';
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from '@/components/ui/select';
import { ScrollArea } from '@/components/ui/scroll-area';
import { Switch } from '@/components/ui/switch';
import { Textarea } from '@/components/ui/textarea';
import { toast } from 'sonner';
import {
  Atom, Play, Download, Copy, Radio,
  Settings, Zap, Eye, FileCode, RotateCcw,
} from 'lucide-react';
import { RADIONUCLIDES } from '@/lib/nuclearMedicine';

interface Props { open: boolean; onOpenChange: (v: boolean) => void; }

type SimulationType = 'pet' | 'spect' | 'cbct' | 'linac';
type PETScanner = 'ge_discovery690' | 'siemens_biograph' | 'philips_vereos' | 'custom';
type SPECTScanner = 'siemens_symbia' | 'ge_discovery_nm' | 'philips_brightview' | 'custom';

export default function GATESimulationDialog({ open, onOpenChange }: Props) {
  const [simType, setSimType] = useState<SimulationType>('pet');
  const [petScanner, setPetScanner] = useState<PETScanner>('ge_discovery690');
  const [spectScanner, setSpectScanner] = useState<SPECTScanner>('siemens_symbia');
  const [selectedNuclide, setSelectedNuclide] = useState('F-18');
  const [activity_MBq, setActivity_MBq] = useState('370');
  const [simulationTime_s, setSimulationTime_s] = useState('60');
  const [numParticles, setNumParticles] = useState('1e7');
  const [phantomType, setPhantomType] = useState('ncat');
  const [addAttenuation, setAddAttenuation] = useState(true);
  const [addScatter, setAddScatter] = useState(true);
  const [addRandoms, setAddRandoms] = useState(true);
  const [addNoise, setAddNoise] = useState(false);
  const [macroCode, setMacroCode] = useState('');
  const [, setShowMacro] = useState(false);

  const nuclide = useMemo(() => RADIONUCLIDES.find(r => r.symbol === selectedNuclide), [selectedNuclide]);

  const generatePETMacro = useCallback((): string => {
    const A_GBq = (parseFloat(activity_MBq) || 370) / 1000;
    const time_s = parseFloat(simulationTime_s) || 60;
    const particles = numParticles;
    const ncid = selectedNuclide.replace('-', '');

    return `# ============================================================
# GATE Macro — PET Simulation (OpenGATE v9.4+)
# Generated by RadShield-MX
# Scanner: ${petScanner}
# Radionuclide: ${selectedNuclide}
# Activity: ${activity_MBq} MBq
# ============================================================

# --- Geometry ---
/gate/geometry/setMaterialDatabase       gate_materials.db
/gate/world/geometry/setXLength            2.0 m
/gate/world/geometry/setYLength            2.0 m
/gate/world/geometry/setZLength            2.0 m
/gate/world/setMaterial                    Air

# --- PET Scanner (${petScanner}) ---
/gate/Scanner/daughters/name               PETCylinder
/gate/Scanner/daughters/insert             cylinder
/gate/PETCylinder/geometry/setRmin         400 mm
/gate/PETCylinder/geometry/setRmax         450 mm
/gate/PETCylinder/geometry/setHeight       200 mm
/gate/PETCylinder/placement/setTranslation 0 0 0 mm
/gate/PETCylinder/setMaterial              LSO

# --- Phantom (${phantomType}) ---
/gate/Phantom/daughters/name               NCATPhantom
/gate/Phantom/daughters/insert             box
/gate/NCATPhantom/geometry/setXLength      500 mm
/gate/NCATPhantom/geometry/setYLength      500 mm
/gate/NCATPhantom/geometry/setZLength      1500 mm
/gate/NCATPhantom/placement/setTranslation 0 0 0 mm
/gate/NCATPhantom/setMaterial              Water

# --- Radionuclide Source ---
/gate/source/addSource                     ${ncid}_source
/gate/source/${ncid}_source/setActivity    ${A_GBq} GBq
/gate/source/${ncid}_source/setType        backtoback
/gate/source/${ncid}_source/gps/type       Volume
/gate/source/${ncid}_source/gps/shape      Cylinder
/gate/source/${ncid}_source/gps/radius     200 mm
/gate/source/${ncid}_source/gps/halfz      500 mm
/gate/source/${ncid}_source/gps/centre     0 0 0 mm
/gate/source/${ncid}_source/gps/particle   ion
/gate/source/${ncid}_source/setForcedUnstableFlag true
/gate/source/${ncid}_source/setForcedHalfLife ${nuclide?.halfLife_hours || 1.83} h

# --- Physics ---
/gate/physics/addPhysicsList               emstandard_opt4
/gate/physics/addProcess                   RadioactiveDecay
/gate/physics/addProcess                   OpticalPhysics
${addScatter ? '/gate/physics/addProcess   Compton' : ''}
${addAttenuation ? '/gate/physics/addProcess Photoelectric' : ''}

# --- Digitizer (Singles → Coincidences) ---
/gate/digitizer/Singles/insert             adder
/gate/digitizer/Singles/insert             readout
/gate/digitizer/Singles/readout/setDepth   1
/gate/digitizer/Singles/insert             blurring
/gate/digitizer/Singles/blurring/setResolution 0.26
/gate/digitizer/Singles/blurring/setEnergyOfReference 511 keV
/gate/digitizer/Coincidences/insert        deadtime
/gate/digitizer/Coincidences/deadtime/setDeadTime 100 ns

# --- Randoms (if enabled) ---
${addRandoms ? '/gate/digitizer/Coincidences/insert delayer\n/gate/digitizer/Coincidences/delayer/setOffset 100 ns' : ''}

# --- Acquisition ---
/gate/application/setTimeStart             0 s
/gate/application/setTimeStop              ${time_s} s
/gate/application/setTotalNumberOfPrimaries ${particles}

# --- Output ---
/gate/output/root/setRootFileName          GATE_PET_${ncid}_${petScanner}_${Date.now()}.root
/gate/output/root/setRootHitFlag           1
/gate/output/root/setRootSinglesFlag       1
/gate/output/root/setRootCoincidencesFlag  1

# --- Initialize & Run ---
/gate/run/initialize
/gate/application/startDAQ
`;
  }, [petScanner, selectedNuclide, activity_MBq, simulationTime_s, numParticles, phantomType, addAttenuation, addScatter, addRandoms, nuclide]);

  const generateSPECTMacro = useCallback((): string => {
    const A_GBq = (parseFloat(activity_MBq) || 370) / 1000;
    const time_s = parseFloat(simulationTime_s) || 60;
    const particles = numParticles;
    const ncid = selectedNuclide.replace('-', '');

    return `# ============================================================
# GATE Macro — SPECT Simulation (OpenGATE v9.4+)
# Generated by RadShield-MX
# Scanner: ${spectScanner}
# Radionuclide: ${selectedNuclide}
# Activity: ${activity_MBq} MBq
# ============================================================

# --- Geometry ---
/gate/geometry/setMaterialDatabase       gate_materials.db
/gate/world/geometry/setXLength            2.0 m
/gate/world/geometry/setYLength            2.0 m
/gate/world/geometry/setZLength            2.0 m

# --- SPECT Scanner (${spectScanner}) ---
/gate/Scanner/daughters/name               SPECTHead
/gate/Scanner/daughters/insert             box
/gate/SPECTHead/geometry/setXLength        600 mm
/gate/SPECTHead/geometry/setYLength        400 mm
/gate/SPECTHead/geometry/setZLength        20 mm
/gate/SPECTHead/placement/setTranslation   300 0 0 mm
/gate/SPECTHead/setMaterial                NaI

# Collimator (LEHR)
/gate/SPECTHead/daughters/name             LEHR
/gate/SPECTHead/daughters/insert           box
/gate/LEHR/geometry/setXLength             600 mm
/gate/LEHR/geometry/setYLength             400 mm
/gate/LEHR/geometry/setZLength             25 mm
/gate/LEHR/placement/setTranslation        -22.5 0 0 mm
/gate/LEHR/setMaterial                     Lead

# --- Phantom ---
/gate/Phantom/daughters/name               Phantom
/gate/Phantom/daughters/insert             cylinder
/gate/Phantom/geometry/setRmin             0 mm
/gate/Phantom/geometry/setRmax             200 mm
/gate/Phantom/geometry/setHeight           500 mm
/gate/Phantom/setMaterial                  Water

# --- Source ---
/gate/source/addSource                     ${ncid}_source
/gate/source/${ncid}_source/setActivity    ${A_GBq} GBq
/gate/source/${ncid}_source/setType        gps
/gate/source/${ncid}_source/gps/type       Volume
/gate/source/${ncid}_source/gps/shape      Sphere
/gate/source/${ncid}_source/gps/radius     150 mm
/gate/source/${ncid}_source/gps/centre     0 0 0 mm
/gate/source/${ncid}_source/gps/particle   gamma
/gate/source/${ncid}_source/gps/energytype Mono
/gate/source/${ncid}_source/gps/monoenergy ${nuclide?.primaryEnergies_keV[0] || 140} keV

# --- Physics ---
/gate/physics/addPhysicsList               emstandard_opt4
${addAttenuation ? '/gate/physics/addProcess Photoelectric' : ''}
${addScatter ? '/gate/physics/addProcess Compton' : ''}

# --- Digitizer ---
/gate/digitizer/Singles/insert             adder
/gate/digitizer/Singles/insert             readout
/gate/digitizer/Singles/readout/setDepth   1
/gate/digitizer/Singles/insert             blurring
/gate/digitizer/Singles/blurring/setResolution 0.10
/gate/digitizer/Singles/blurring/setEnergyOfReference ${nuclide?.primaryEnergies_keV[0] || 140} keV
/gate/digitizer/Singles/insert             thresholder
/gate/digitizer/Singles/thresholder/setThreshold ${((nuclide?.primaryEnergies_keV[0] || 140) * 0.9).toFixed(0)} keV
/gate/digitizer/Singles/insert             upholder
/gate/digitizer/Singles/upholder/setUpholder ${((nuclide?.primaryEnergies_keV[0] || 140) * 1.1).toFixed(0)} keV

# --- Acquisition ---
/gate/application/setTimeStart             0 s
/gate/application/setTimeStop              ${time_s} s
/gate/application/setTotalNumberOfPrimaries ${particles}

# --- Output ---
/gate/output/root/setRootFileName          GATE_SPECT_${ncid}_${spectScanner}_${Date.now()}.root
/gate/output/root/setRootSinglesFlag       1

# --- Run ---
/gate/run/initialize
/gate/application/startDAQ
`;
  }, [spectScanner, selectedNuclide, activity_MBq, simulationTime_s, numParticles, addAttenuation, addScatter, nuclide]);

  const generateMacro = useCallback(() => {
    const macro = simType === 'pet' ? generatePETMacro() : generateSPECTMacro();
    setMacroCode(macro);
    setShowMacro(true);
    toast.success(`${simType.toUpperCase()} macro generated`);
  }, [simType, generatePETMacro, generateSPECTMacro]);

  const downloadMacro = useCallback(() => {
    const blob = new Blob([macroCode], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `GATE_${simType}_${selectedNuclide.replace('-', '')}_${Date.now()}.mac`;
    a.click();
    URL.revokeObjectURL(url);
    toast.success('Macro downloaded');
  }, [macroCode, simType, selectedNuclide]);

  const copyMacro = useCallback(() => {
    navigator.clipboard.writeText(macroCode);
    toast.success('Copied to clipboard');
  }, [macroCode]);

  const petNuclides = RADIONUCLIDES.filter(r => r.category === 'PET');
  const spectNuclides = RADIONUCLIDES.filter(r => r.category === 'SPECT');
  const currentNuclides = simType === 'pet' ? petNuclides : spectNuclides;

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="max-w-5xl max-h-[92vh] overflow-hidden flex flex-col">
        <DialogHeader>
          <DialogTitle className="flex items-center gap-2 text-lg">
            <Atom className="h-5 w-5 text-cyan-500" />
            GATE Simulation — PET / SPECT
            <Badge variant="outline" className="text-[10px]">OpenGATE v9.4+</Badge>
          </DialogTitle>
          <p className="text-sm text-muted-foreground">
            Geant4 Application for Tomographic Emission — Full MC simulation for nuclear medicine imaging
          </p>
        </DialogHeader>

        <Tabs defaultValue="setup" className="flex-1 flex flex-col min-h-0">
          <TabsList className="grid w-full grid-cols-4 shrink-0">
            <TabsTrigger value="setup"><Settings className="h-3.5 w-3.5 mr-1" />Setup</TabsTrigger>
            <TabsTrigger value="physics"><Zap className="h-3.5 w-3.5 mr-1" />Physics</TabsTrigger>
            <TabsTrigger value="macro"><FileCode className="h-3.5 w-3.5 mr-1" />Macro</TabsTrigger>
            <TabsTrigger value="results"><Eye className="h-3.5 w-3.5 mr-1" />Results</TabsTrigger>
          </TabsList>

          <ScrollArea className="flex-1 pr-2">
            <div className="space-y-3 pb-2">
              {/* SETUP */}
              <TabsContent value="setup" className="space-y-3 mt-2">
                <div className="grid grid-cols-2 gap-3">
                  {/* Sim Type */}
                  <Card>
                    <CardHeader className="pb-2"><CardTitle className="text-sm">Simulation Type</CardTitle></CardHeader>
                    <CardContent>
                      <div className="flex gap-2">
                        <Button size="sm" variant={simType === 'pet' ? 'default' : 'outline'} className="flex-1" onClick={() => setSimType('pet')}><Radio className="h-3.5 w-3.5 mr-1" />PET</Button>
                        <Button size="sm" variant={simType === 'spect' ? 'default' : 'outline'} className="flex-1" onClick={() => setSimType('spect')}><Radio className="h-3.5 w-3.5 mr-1" />SPECT</Button>
                      </div>
                    </CardContent>
                  </Card>
                  {/* Scanner */}
                  <Card>
                    <CardHeader className="pb-2"><CardTitle className="text-sm">Scanner</CardTitle></CardHeader>
                    <CardContent>
                      {simType === 'pet' ? (
                        <Select value={petScanner} onValueChange={(v) => setPetScanner(v as PETScanner)}>
                          <SelectTrigger><SelectValue /></SelectTrigger>
                          <SelectContent>
                            <SelectItem value="ge_discovery690">GE Discovery 690</SelectItem>
                            <SelectItem value="siemens_biograph">Siemens Biograph</SelectItem>
                            <SelectItem value="philips_vereos">Philips Vereos</SelectItem>
                            <SelectItem value="custom">Custom</SelectItem>
                          </SelectContent>
                        </Select>
                      ) : (
                        <Select value={spectScanner} onValueChange={(v) => setSpectScanner(v as SPECTScanner)}>
                          <SelectTrigger><SelectValue /></SelectTrigger>
                          <SelectContent>
                            <SelectItem value="siemens_symbia">Siemens Symbia</SelectItem>
                            <SelectItem value="ge_discovery_nm">GE Discovery NM</SelectItem>
                            <SelectItem value="philips_brightview">Philips BrightView</SelectItem>
                            <SelectItem value="custom">Custom</SelectItem>
                          </SelectContent>
                        </Select>
                      )}
                    </CardContent>
                  </Card>
                </div>

                {/* Radionuclide */}
                <Card>
                  <CardHeader className="pb-2"><CardTitle className="text-sm">Radionuclide</CardTitle></CardHeader>
                  <CardContent className="space-y-2">
                    <Select value={selectedNuclide} onValueChange={setSelectedNuclide}>
                      <SelectTrigger><SelectValue /></SelectTrigger>
                      <SelectContent>
                        {currentNuclides.map(r => (
                          <SelectItem key={r.symbol} value={r.symbol}>
                            {r.symbol} — {r.name} (E={r.primaryEnergies_keV.join(',')} keV, T1/2={r.halfLife_text})
                          </SelectItem>
                        ))}
                      </SelectContent>
                    </Select>
                    {nuclide && (
                      <div className="grid grid-cols-4 gap-2 text-xs bg-muted p-2 rounded">
                        <div><span className="text-muted-foreground">Energy:</span> {nuclide.primaryEnergies_keV.join(', ')} keV</div>
                        <div><span className="text-muted-foreground">T1/2:</span> {nuclide.halfLife_text}</div>
                        <div><span className="text-muted-foreground">Γ:</span> {nuclide.gammaConstant_mSv_m2_GBq_h} mSv.m2/GBq.h</div>
                        <div><span className="text-muted-foreground">HVL(Pb):</span> {nuclide.HVL_lead_mm} mm</div>
                      </div>
                    )}
                  </CardContent>
                </Card>

                {/* Parameters */}
                <div className="grid grid-cols-4 gap-2">
                  <div><Label className="text-xs">Activity (MBq)</Label><Input type="number" value={activity_MBq} onChange={e => setActivity_MBq(e.target.value)} /></div>
                  <div><Label className="text-xs">Time (s)</Label><Input type="number" value={simulationTime_s} onChange={e => setSimulationTime_s(e.target.value)} /></div>
                  <div><Label className="text-xs">Particles</Label><Input value={numParticles} onChange={e => setNumParticles(e.target.value)} /></div>
                  <div><Label className="text-xs">Phantom</Label>
                    <Select value={phantomType} onValueChange={setPhantomType}>
                      <SelectTrigger><SelectValue /></SelectTrigger>
                      <SelectContent>
                        <SelectItem value="ncat">NCAT</SelectItem>
                        <SelectItem value="water_cylinder">Water Cylinder</SelectItem>
                        <SelectItem value="nema">NEMA IQ</SelectItem>
                        <SelectItem value="anthropomorphic">Anthropomorphic</SelectItem>
                      </SelectContent>
                    </Select>
                  </div>
                </div>

                <Button onClick={generateMacro} className="w-full"><Play className="h-4 w-4 mr-2" />Generate GATE Macro</Button>
              </TabsContent>

              {/* PHYSICS */}
              <TabsContent value="physics" className="space-y-3 mt-2">
                <div className="grid grid-cols-2 gap-3">
                  <Card>
                    <CardHeader className="pb-2"><CardTitle className="text-sm">Physics Processes</CardTitle></CardHeader>
                    <CardContent className="space-y-2">
                      <div className="flex items-center justify-between"><Label className="text-xs">Photoelectric effect</Label><Switch checked={addAttenuation} onCheckedChange={setAddAttenuation} /></div>
                      <div className="flex items-center justify-between"><Label className="text-xs">Compton scatter</Label><Switch checked={addScatter} onCheckedChange={setAddScatter} /></div>
                      <div className="flex items-center justify-between"><Label className="text-xs">Random coincidences</Label><Switch checked={addRandoms} onCheckedChange={setAddRandoms} /></div>
                      <div className="flex items-center justify-between"><Label className="text-xs">Add noise</Label><Switch checked={addNoise} onCheckedChange={setAddNoise} /></div>
                    </CardContent>
                  </Card>
                  <Card>
                    <CardHeader className="pb-2"><CardTitle className="text-sm">Physics List</CardTitle></CardHeader>
                    <CardContent className="text-xs space-y-1">
                      <p><strong>emstandard_opt4</strong> — EM standard_opt4 (recommended for medical physics)</p>
                      <p className="text-muted-foreground">Electromagnetic processes optimized for medical applications. Includes photoelectric effect, Compton scattering, pair production, bremsstrahlung, ionization.</p>
                      <Separator className="my-1" />
                      <p><strong>Decay processes:</strong></p>
                      <p className="text-muted-foreground">RadioactiveDecay, OpticalPhysics, IonIonisation</p>
                    </CardContent>
                  </Card>
                </div>
              </TabsContent>

              {/* MACRO */}
              <TabsContent value="macro" className="space-y-3 mt-2">
                {macroCode ? (
                  <>
                    <div className="flex gap-2">
                      <Button size="sm" onClick={downloadMacro}><Download className="h-3.5 w-3.5 mr-1" />Download .mac</Button>
                      <Button size="sm" variant="outline" onClick={copyMacro}><Copy className="h-3.5 w-3.5 mr-1" />Copy</Button>
                      <Button size="sm" variant="ghost" onClick={() => setShowMacro(false)}><RotateCcw className="h-3.5 w-3.5 mr-1" />Clear</Button>
                    </div>
                    <Textarea value={macroCode} readOnly className="font-mono text-xs h-[400px] bg-slate-950 text-green-400" />
                  </>
                ) : (
                  <div className="text-center py-8 text-muted-foreground">
                    <FileCode className="h-12 w-12 mx-auto mb-2 opacity-30" />
                    <p>Generate a macro in the Setup tab first</p>
                  </div>
                )}
              </TabsContent>

              {/* RESULTS */}
              <TabsContent value="results" className="space-y-3 mt-2">
                <Card className="bg-blue-50 dark:bg-blue-950/30 border-blue-200">
                  <CardContent className="pt-4 text-sm text-blue-700 dark:text-blue-300">
                    <p className="font-medium">GATE Output Format</p>
                    <p>GATE produces ROOT files with Hits, Singles, and Coincidences trees. Analysis can be performed with Root/Geant4 analysis tools or converted to Sinograms for image reconstruction.</p>
                  </CardContent>
                </Card>
                <div className="grid grid-cols-2 gap-3">
                  <Card><CardHeader className="pb-2"><CardTitle className="text-sm">Output Files</CardTitle></CardHeader><CardContent className="text-xs space-y-1">
                    <p>• <strong>.root</strong> — Hits, Singles, Coincidences</p>
                    <p>• <strong>.mac</strong> — GATE macro (this file)</p>
                    <p>• <strong>.log</strong> — Simulation log</p>
                    <p>• <strong>_sinogram.root</strong> — Reconstructed sinograms</p>
                  </CardContent></Card>
                  <Card><CardHeader className="pb-2"><CardTitle className="text-sm">Post-processing</CardTitle></CardHeader><CardContent className="text-xs space-y-1">
                    <p>• RootAnalysis (C++)</p>
                    <p>• CASToR reconstruction</p>
                    <p>• STIR image reconstruction</p>
                    <p>• Python + uproot/awkward</p>
                  </CardContent></Card>
                </div>
                <Card><CardHeader className="pb-2"><CardTitle className="text-sm">Command to Run</CardTitle></CardHeader><CardContent>
                  <code className="text-xs font-mono bg-muted p-2 rounded block">Gate GATE_PET_{selectedNuclide.replace('-', '')}_{petScanner}.mac</code>
                </CardContent></Card>
              </TabsContent>
            </div>
          </ScrollArea>
        </Tabs>
      </DialogContent>
    </Dialog>
  );
}
